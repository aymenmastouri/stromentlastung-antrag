-- Vorgang: Anträge, Nachweise, nur anfügbares Vorgangsprotokoll (Fachkonzept Kap. 4, 5 und 9).
CREATE TABLE antrag (
    id                                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aktenzeichen                       VARCHAR(40)  NOT NULL UNIQUE,
    unternehmen_kennung                VARCHAR(12)  NOT NULL,
    dienststelle                       VARCHAR(8)   NOT NULL,
    entnahmejahr                       INT          NOT NULL,
    zustand                            VARCHAR(24)  NOT NULL,
    versteuert_kwh                     BIGINT       NOT NULL,
    elektromobilitaet_kwh              BIGINT       NOT NULL,
    elektromobilitaet_geschaetzt       BOOLEAN      NOT NULL,
    nutzenergie_dritte_kwh             BIGINT       NOT NULL,
    versicherung_keine_rueckforderung  BOOLEAN      NOT NULL,
    versicherung_keine_schwierigkeiten BOOLEAN      NOT NULL,
    selbsterklaerung_beihilfen         BOOLEAN      NOT NULL,
    selbstberechnet_cent               BIGINT,
    nachberechnet_cent                 BIGINT,
    festgesetzt_cent                   BIGINT,
    eingereicht_am                     DATE,
    antragsjahr                        INT,
    bestandskraeftig_ab                DATE,
    bearbeitung                        VARCHAR(120),
    bearbeitung_konto                  VARCHAR(120),
    entscheidung_vorschlag             VARCHAR(12),
    entscheidung_grund                 VARCHAR(60),
    entscheidung_begruendung           VARCHAR(4000),
    gezeichnet_von                     VARCHAR(120),
    gezeichnet_von_konto               VARCHAR(120),
    rueckfrage_text                    VARCHAR(4000),
    rueckfrage_frist_ende              DATE,
    rueckfrage_antwort                 VARCHAR(4000),
    pruefvermerk                       VARCHAR(4000),
    korrigiert_versteuert_kwh          BIGINT,
    korrigiert_elektromobilitaet_kwh   BIGINT,
    korrigiert_nutzenergie_dritte_kwh  BIGINT,
    aenderung_begruendung              VARCHAR(4000),
    bisher_festgesetzt_cent            BIGINT,
    rueckforderung_cent                BIGINT,
    letzter_bescheid                   VARCHAR(48),
    angelegt_am                        TIMESTAMP WITH TIME ZONE NOT NULL,
    geaendert_am                       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_antrag_unternehmen ON antrag (unternehmen_kennung);
CREATE INDEX ix_antrag_dienststelle_zustand ON antrag (dienststelle, zustand);

CREATE TABLE nachweis (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aktenzeichen    VARCHAR(40)  NOT NULL REFERENCES antrag (aktenzeichen),
    versorger       VARCHAR(200) NOT NULL,
    zeitraum_von    DATE         NOT NULL,
    zeitraum_bis    DATE         NOT NULL,
    menge_kwh       BIGINT       NOT NULL,
    verwendungszweck VARCHAR(200) NOT NULL,
    belegnummer     VARCHAR(60),
    geprueft        BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE vorgangsereignis (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aktenzeichen     VARCHAR(40)  NOT NULL,
    zeitpunkt        TIMESTAMP WITH TIME ZONE NOT NULL,
    akteur           VARCHAR(120) NOT NULL,
    rolle            VARCHAR(24)  NOT NULL,
    art              VARCHAR(32)  NOT NULL,
    zustand_vorher   VARCHAR(24),
    zustand_nachher  VARCHAR(24),
    bemerkung        VARCHAR(4000),
    bescheid_kennung VARCHAR(48),
    zahlung_kennung  VARCHAR(24),
    intern           BOOLEAN      NOT NULL
);
CREATE INDEX ix_ereignis_aktenzeichen ON vorgangsereignis (aktenzeichen);

-- Revisionssicherheit (Kap. 9): Vorgangsereignisse können weder geändert noch gelöscht werden.
CREATE TRIGGER trg_ereignis_unveraenderlich BEFORE UPDATE, DELETE ON vorgangsereignis FOR EACH ROW
    CALL "de.stromentlastung.antrag.protokoll.UnveraenderlichTrigger";
